import type {
  ComponentName,
  ComponentStyle,
  ExplicitProps,
  StyleDesign,
} from "./style-design.js";

export const HEADING_COMMANDS = [
  "section",
  "subsection",
  "subsubsection",
  "paragraph",
  "subparagraph",
] as const;

export const GEOMETRY_PAPER = {
  A4: "a4paper",
  Letter: "letterpaper",
  Legal: "legalpaper",
};

export const ALIGN_COMMAND = {
  left: "\\raggedright",
  right: "\\raggedleft",
  center: "\\centering",
  justify: "",
} as const;

export const num = (value: number) => `${+value.toFixed(3)}`;

export const line = (size: number) => num(size * 1.2);

/** Font size, weight, shape and colour commands for one component. */
export function fontCommands(
  props: ComponentStyle,
  color: string | undefined,
): string {
  let out = "";

  if (props.fontSizePt !== undefined) {
    out += `\\fontsize{${num(props.fontSizePt)}pt}{${line(props.fontSizePt)}pt}\\selectfont`;
  }

  if (props.bold !== undefined) out += props.bold ? "\\bfseries" : "\\mdseries";

  if (props.italic !== undefined)
    out += props.italic ? "\\itshape" : "\\upshape";

  if (color) out += `\\color{${color}}`;

  return out;
}

/** Shared state for the section builders that make up a preamble. */
export interface LatexContext {
  design: StyleDesign;
  explicit: ExplicitProps;
  /** Preamble lines in output order. */
  out: string[];
  warnings: string[];
  get(name: ComponentName): ComponentStyle | undefined;
  /** Registers a colour (once) and returns its name, or undefined for no colour. */
  color(id: string, value: string | undefined): string | undefined;
  /** Warns about properties the researcher changed that LaTeX cannot express. */
  unsupported(
    name: ComponentName,
    keys: readonly (keyof ComponentStyle)[],
    reason: string,
  ): void;
  /** Warns that a component the researcher changed cannot be expressed at all. */
  wholly(name: ComponentName, reason: string): void;
  /** Colour definitions, emitted after xcolor is loaded. */
  colors: Map<string, string>;
}

export function createLatexContext(
  design: StyleDesign,
  explicit: ExplicitProps,
): LatexContext {
  const warnings: string[] = [];
  const colors = new Map<string, string>();

  return {
    design,
    explicit,
    out: ["% Generated by Academic Writer from design.json"],
    warnings,
    colors,
    get: (name) => design.components[name],
    color: (id, value) => {
      if (!value) return undefined;

      if (!colors.has(id)) {
        colors.set(
          id,
          `\\definecolor{${id}}{HTML}{${value.slice(1).toUpperCase()}}`,
        );
      }

      return id;
    },
    unsupported: (name, keys, reason) => {
      const changed = explicit.get(name);

      if (!changed) return;

      for (const key of keys) {
        if (changed.has(key)) {
          warnings.push(
            `latex: components.${name}.${key} is not applied; ${reason}`,
          );
        }
      }
    },
    wholly: (name, reason) => {
      if (explicit.has(name))
        warnings.push(`latex: components.${name} is not applied; ${reason}`);
    },
  };
}
