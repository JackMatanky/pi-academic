import type { ExplicitProps } from "./style-design.js";
import type {
  ComponentName,
  ComponentStyle,
  StyleDesign,
} from "./style-design.js";

export interface BuiltPreamble {
  tex: string;
  warnings: string[];
}

const HEADING_COMMANDS = [
  "section",
  "subsection",
  "subsubsection",
  "paragraph",
  "subparagraph",
] as const;

const GEOMETRY_PAPER = {
  A4: "a4paper",
  Letter: "letterpaper",
  Legal: "legalpaper",
};
const ALIGN_COMMAND = {
  left: "\\raggedright",
  right: "\\raggedleft",
  center: "\\centering",
  justify: "",
} as const;

const num = (value: number) => `${+value.toFixed(3)}`;
const line = (size: number) => num(size * 1.2);

/** Font size, weight, shape and colour commands for one component. */
function fontCommands(
  props: ComponentStyle,
  color: string | undefined,
): string {
  let out = "";
  if (props.fontSizePt !== undefined) {
    out += `\\fontsize{${num(props.fontSizePt)}pt}{${line(props.fontSizePt)}pt}\\selectfont`;
  }
  if (props.bold !== undefined) out += props.bold ? "\\bfseries" : "\\mdseries";
  if (props.italic !== undefined)
    out += props.italic ? "\\itshape" : "\\upshape";
  if (color) out += `\\color{${color}}`;
  return out;
}

/**
 * Generate the preamble `design.json` describes. Components the LaTeX
 * output cannot express are reported in `warnings` rather than dropped.
 */
export function buildLatexPreamble(
  design: StyleDesign,
  explicit: ExplicitProps,
): BuiltPreamble {
  const warnings: string[] = [];
  const out: string[] = ["% Generated by Academic Writer from design.json"];
  const colors = new Map<string, string>();
  const get = (name: ComponentName): ComponentStyle | undefined =>
    design.components[name];

  const color = (id: string, value: string | undefined): string | undefined => {
    if (!value) return undefined;
    if (!colors.has(id)) {
      colors.set(
        id,
        `\\definecolor{${id}}{HTML}{${value.slice(1).toUpperCase()}}`,
      );
    }
    return id;
  };

  const unsupported = (
    name: ComponentName,
    keys: readonly (keyof ComponentStyle)[],
    reason: string,
  ) => {
    const changed = explicit.get(name);
    if (!changed) return;
    for (const key of keys) {
      if (changed.has(key)) {
        warnings.push(
          `latex: components.${name}.${key} is not applied; ${reason}`,
        );
      }
    }
  };
  const wholly = (name: ComponentName, reason: string) => {
    if (explicit.has(name))
      warnings.push(`latex: components.${name} is not applied; ${reason}`);
  };

  const { page } = design;
  const m = page.marginsMm;
  const geometry = [
    GEOMETRY_PAPER[page.size],
    `top=${num(m.top)}mm`,
    `bottom=${num(m.bottom)}mm`,
    `left=${num(m.left)}mm`,
    `right=${num(m.right)}mm`,
  ];
  if (page.orientation === "landscape") geometry.push("landscape");
  // Word measures the footer from the page edge; LaTeX measures footskip from the text block.
  if (page.footerDistanceMm !== undefined && page.footerDistanceMm < m.bottom) {
    geometry.push(`footskip=${num(m.bottom - page.footerDistanceMm)}mm`);
  }
  out.push(
    "\\usepackage{iftex}",
    `\\usepackage[${geometry.join(",")}]{geometry}`,
    "\\usepackage{xcolor}",
    "\\usepackage{colortbl}",
    "\\usepackage{setspace}",
    "\\usepackage{etoolbox}",
    "\\usepackage{titlesec}",
    "\\usepackage{titling}",
    "\\usepackage{fancyhdr}",
    "\\usepackage{caption}",
  );

  const body = get("body") ?? {};
  const body_color = color("awbody", body.color);
  const fontLines: string[] = [];
  if (body.fontFamily) {
    fontLines.push(
      `\\IfFontExistsTF{${body.fontFamily}}{\\setmainfont{${body.fontFamily}}}{}`,
    );
  }
  const code = get("code");
  if (code?.fontFamily) {
    fontLines.push(
      `\\IfFontExistsTF{${code.fontFamily}}{\\setmonofont{${code.fontFamily}}}{}`,
    );
  }
  if (fontLines.length) {
    out.push("\\iftutex", "\\usepackage{fontspec}", ...fontLines, "\\fi");
  }

  out.push("\\makeatletter");
  if (body.fontSizePt !== undefined) {
    out.push(
      `\\renewcommand\\normalsize{\\@setfontsize\\normalsize{${num(body.fontSizePt)}pt}{${line(body.fontSizePt)}pt}}`,
      "\\AtBeginDocument{\\normalsize}",
    );
  }
  out.push("\\makeatother");
  if (body.lineSpacing !== undefined)
    out.push(`\\AtBeginDocument{\\setstretch{${num(body.lineSpacing)}}}`);
  if (body.alignment && ALIGN_COMMAND[body.alignment]) {
    out.push(`\\AtBeginDocument{${ALIGN_COMMAND[body.alignment]}}`);
  }
  if (body.firstLineIndentMm !== undefined) {
    out.push(
      `\\AtBeginDocument{\\setlength{\\parindent}{${num(body.firstLineIndentMm)}mm}}`,
    );
  }
  if (body.spaceAfterPt !== undefined) {
    out.push(
      `\\AtBeginDocument{\\setlength{\\parskip}{${num(body.spaceAfterPt)}pt}}`,
    );
  }
  if (body_color) out.push(`\\AtBeginDocument{\\color{${body_color}}}`);
  unsupported(
    "body",
    [
      "bold",
      "italic",
      "underline",
      "indentLeftMm",
      "indentRightMm",
      "hangingIndentMm",
      "spaceBeforePt",
      "keepWithNext",
      "pageBreakBefore",
      "shading",
      "borderWidthPt",
      "borderColor",
    ],
    "LaTeX applies body text settings document-wide only for the listed properties",
  );

  // Headings: Pandoc's LaTeX writer has no command for level 6.
  HEADING_COMMANDS.forEach((command, index) => {
    const name = `heading${index + 1}` as ComponentName;
    const props = get(name);
    if (!props) return;
    const hc = color(`awheading${index + 1}`, props.color);
    const align = props.alignment ? ALIGN_COMMAND[props.alignment] : "";
    const underline = props.underline ? "\\underline" : "";
    out.push(
      `\\titleformat{\\${command}}[hang]{\\normalfont${fontCommands(props, hc)}${align}}{\\the${command}}{1em}{${underline}}`,
      `\\titlespacing*{\\${command}}{${num(props.indentLeftMm ?? 0)}mm}{${num(props.spaceBeforePt ?? 12)}pt}{${num(props.spaceAfterPt ?? 6)}pt}`,
    );
    if (props.pageBreakBefore)
      out.push(`\\pretocmd{\\${command}}{\\clearpage}{}{}`);
    if (props.keepWithNext === false && explicit.has(name)) {
      warnings.push(
        `latex: components.${name}.keepWithNext=false is not applied; titlesec always keeps headings with the next paragraph`,
      );
    }
    unsupported(
      name,
      [
        "shading",
        "borderWidthPt",
        "borderColor",
        "lineSpacing",
        "indentRightMm",
        "firstLineIndentMm",
        "hangingIndentMm",
      ],
      "headings take font, alignment, spacing, left indent, and page-break settings in LaTeX",
    );
  });
  wholly(
    "heading6",
    "Pandoc's LaTeX writer has no sectioning command for level 6",
  );

  const title = get("title");
  if (title) {
    const tc = color("awtitle", title.color);
    const env = {
      left: "flushleft",
      right: "flushright",
      center: "center",
      justify: "center",
    }[title.alignment ?? "center"];
    out.push(
      `\\pretitle{${title.spaceBeforePt ? `\\vspace*{${num(title.spaceBeforePt)}pt}` : ""}\\begin{${env}}${fontCommands(title, tc)}}`,
      `\\posttitle{\\par\\end{${env}}${title.spaceAfterPt ? `\\vskip ${num(title.spaceAfterPt)}pt` : ""}}`,
    );
    unsupported(
      "title",
      [
        "underline",
        "lineSpacing",
        "indentLeftMm",
        "indentRightMm",
        "firstLineIndentMm",
        "hangingIndentMm",
        "keepWithNext",
        "pageBreakBefore",
        "shading",
        "borderWidthPt",
        "borderColor",
      ],
      "titling accepts font, alignment, and spacing only",
    );
  }
  wholly(
    "subtitle",
    "Pandoc appends the subtitle to the title in LaTeX, so it cannot be styled separately",
  );
  wholly(
    "abstractHeading",
    "the abstract title is generated by the document class",
  );

  const abstract = get("abstractBody");
  if (abstract) {
    const ac = color("awabstract", abstract.color);
    const spacing =
      abstract.lineSpacing !== undefined
        ? `\\setstretch{${num(abstract.lineSpacing)}}`
        : "";
    const align = abstract.alignment ? ALIGN_COMMAND[abstract.alignment] : "";
    out.push(
      `\\AtBeginEnvironment{abstract}{${fontCommands(abstract, ac)}${spacing}${align}}`,
    );
    unsupported(
      "abstractBody",
      [
        "indentLeftMm",
        "indentRightMm",
        "spaceBeforePt",
        "spaceAfterPt",
        "firstLineIndentMm",
        "hangingIndentMm",
        "keepWithNext",
        "pageBreakBefore",
        "underline",
        "shading",
        "borderWidthPt",
        "borderColor",
      ],
      "the abstract environment takes font, spacing, and alignment settings only",
    );
  }

  const quote = get("blockQuote");
  if (quote) {
    const qc = color("awquote", quote.color);
    out.push(
      `\\renewenvironment{quote}{\\list{}{\\leftmargin=${num(quote.indentLeftMm ?? 10)}mm\\rightmargin=${num(quote.indentRightMm ?? 0)}mm\\topsep=${num(quote.spaceBeforePt ?? 6)}pt\\partopsep=0pt}\\item\\relax${fontCommands(quote, qc)}${quote.lineSpacing !== undefined ? `\\setstretch{${num(quote.lineSpacing)}}` : ""}}{\\endlist\\vspace{${num(quote.spaceAfterPt ?? 0)}pt}}`,
    );
    unsupported(
      "blockQuote",
      [
        "underline",
        "alignment",
        "firstLineIndentMm",
        "hangingIndentMm",
        "keepWithNext",
        "pageBreakBefore",
        "shading",
        "borderWidthPt",
        "borderColor",
      ],
      "block quotes take font, spacing, and margins only",
    );
  }

  const footnote = get("footnoteText");
  if (footnote) {
    const fc = color("awfootnote", footnote.color);
    // setspace's \setstretch re-runs \@currsize, which is \footnotesize here, and
    // recurses forever; line spacing therefore goes into the explicit leading.
    const leading =
      footnote.fontSizePt === undefined
        ? undefined
        : footnote.fontSizePt * 1.2 * (footnote.lineSpacing ?? 1);
    out.push("\\makeatletter");
    if (footnote.fontSizePt !== undefined && leading !== undefined) {
      out.push(
        `\\renewcommand\\footnotesize{\\@setfontsize\\footnotesize{${num(footnote.fontSizePt)}pt}{${num(leading)}pt}${fontCommands({ ...footnote, fontSizePt: undefined }, fc)}}`,
      );
    } else if (fontCommands(footnote, fc)) {
      out.push(`\\apptocmd{\\footnotesize}{${fontCommands(footnote, fc)}}{}{}`);
    }
    out.push("\\makeatother");
    if (
      footnote.fontSizePt === undefined &&
      footnote.lineSpacing !== undefined
    ) {
      if (explicit.get("footnoteText")?.has("lineSpacing")) {
        warnings.push(
          "latex: components.footnoteText.lineSpacing is not applied; set fontSizePt too so the footnote leading can be computed",
        );
      }
    }
    if (footnote.spaceAfterPt !== undefined)
      out.push(`\\setlength{\\footnotesep}{${num(footnote.spaceAfterPt)}pt}`);
    unsupported(
      "footnoteText",
      [
        "alignment",
        "indentLeftMm",
        "indentRightMm",
        "firstLineIndentMm",
        "hangingIndentMm",
        "spaceBeforePt",
        "keepWithNext",
        "pageBreakBefore",
        "underline",
        "shading",
        "borderWidthPt",
        "borderColor",
      ],
      "footnote text takes font, spacing, and footnote separation settings only",
    );
  }
  const mark = get("footnoteReference");
  if (mark) {
    const mc = color("awfnmark", mark.color);
    const style = fontCommands(mark, mc);
    if (style) {
      out.push(
        "\\makeatletter",
        `\\renewcommand\\@makefnmark{\\hbox{\\@textsuperscript{\\normalfont${style}\\@thefnmark}}}`,
        "\\makeatother",
      );
    }
    unsupported(
      "footnoteReference",
      ["underline"],
      "footnote marks cannot be underlined in LaTeX",
    );
  }

  const bib = get("bibliography");
  if (bib) {
    const bc = color("awbib", bib.color);
    const spacing =
      bib.lineSpacing !== undefined
        ? `\\setstretch{${num(bib.lineSpacing)}}`
        : "";
    const style = `${fontCommands(bib, bc)}${spacing}`;
    if (style) out.push(`\\AtBeginEnvironment{CSLReferences}{${style}}`);
    unsupported(
      "bibliography",
      [
        "spaceAfterPt",
        "spaceBeforePt",
        "hangingIndentMm",
        "indentLeftMm",
        "indentRightMm",
        "firstLineIndentMm",
        "alignment",
        "underline",
        "keepWithNext",
        "pageBreakBefore",
        "shading",
        "borderWidthPt",
        "borderColor",
      ],
      "Pandoc's CSLReferences environment sets indentation and entry spacing itself",
    );
  }
  wholly(
    "citation",
    "Pandoc emits citations as plain text with no style to attach to",
  );

  const lists = [get("orderedList"), get("bulletList")];
  if (lists.some(Boolean)) {
    out.push("\\usepackage{enumitem}");
    (["orderedList", "bulletList"] as const).forEach((name, index) => {
      const props = lists[index];
      if (!props) return;
      const env = name === "orderedList" ? "enumerate" : "itemize";
      const options: string[] = [];
      if (props.indentLeftMm !== undefined)
        options.push(`leftmargin=${num(props.indentLeftMm)}mm`);
      if (props.spaceAfterPt !== undefined)
        options.push(`itemsep=${num(props.spaceAfterPt)}pt`);
      if (props.spaceBeforePt !== undefined)
        options.push(`topsep=${num(props.spaceBeforePt)}pt`);
      if (options.length) out.push(`\\setlist[${env}]{${options.join(",")}}`);
      unsupported(
        name,
        [
          "fontFamily",
          "fontSizePt",
          "lineSpacing",
          "bold",
          "italic",
          "underline",
          "color",
          "shading",
          "alignment",
          "indentRightMm",
          "firstLineIndentMm",
          "hangingIndentMm",
          "keepWithNext",
          "pageBreakBefore",
          "borderWidthPt",
          "borderColor",
        ],
        "lists take left indent and item/list spacing only",
      );
    });
  }

  const table = get("table");
  if (table) {
    if (table.cellPaddingMm !== undefined)
      out.push(`\\setlength{\\tabcolsep}{${num(table.cellPaddingMm)}mm}`);
    const rule = [
      table.borderWidthPt !== undefined
        ? `\\setlength{\\heavyrulewidth}{${num(table.borderWidthPt)}pt}\\setlength{\\lightrulewidth}{${num(table.borderWidthPt)}pt}`
        : "",
      table.borderColor
        ? `\\arrayrulecolor{${color("awrule", table.borderColor)}}`
        : "",
    ].join("");
    // booktabs is only loaded when the document contains a table.
    if (rule)
      out.push(`\\AtBeginDocument{\\ifdefined\\heavyrulewidth${rule}\\fi}`);
    unsupported(
      "table",
      [
        "fontFamily",
        "fontSizePt",
        "lineSpacing",
        "bold",
        "italic",
        "underline",
        "color",
        "shading",
        "alignment",
        "spaceBeforePt",
        "spaceAfterPt",
        "indentLeftMm",
        "indentRightMm",
        "firstLineIndentMm",
        "hangingIndentMm",
        "keepWithNext",
        "pageBreakBefore",
      ],
      "tables take cell padding and rule width/colour only",
    );
  }
  wholly(
    "tableHeader",
    "Pandoc's LaTeX tables carry no header-row hook to style",
  );
  wholly("tableBody", "Pandoc's LaTeX tables carry no body-cell hook to style");

  const caption = get("caption");
  if (caption) {
    const cc = color("awcaption", caption.color);
    const fontMacro = fontCommands(caption, cc);
    const options: string[] = [];
    if (fontMacro) {
      out.push(`\\DeclareCaptionFont{awcaption}{${fontMacro}}`);
      options.push("font=awcaption");
    }
    if (caption.alignment) {
      options.push(
        `justification=${{ left: "raggedright", right: "raggedleft", center: "centering", justify: "justified" }[caption.alignment]}`,
      );
    }
    if (caption.spaceBeforePt !== undefined)
      options.push(`aboveskip=${num(caption.spaceBeforePt)}pt`);
    if (caption.spaceAfterPt !== undefined)
      options.push(`belowskip=${num(caption.spaceAfterPt)}pt`);
    if (options.length) out.push(`\\captionsetup{${options.join(",")}}`);
    unsupported(
      "caption",
      [
        "lineSpacing",
        "underline",
        "indentLeftMm",
        "indentRightMm",
        "firstLineIndentMm",
        "hangingIndentMm",
        "keepWithNext",
        "pageBreakBefore",
        "shading",
        "borderWidthPt",
        "borderColor",
      ],
      "captions take font, alignment, and spacing only",
    );
  }
  const figure = get("figure");
  if (figure?.alignment && ALIGN_COMMAND[figure.alignment]) {
    out.push(
      `\\AtBeginEnvironment{figure}{${ALIGN_COMMAND[figure.alignment]}}`,
    );
  }
  if (figure) {
    unsupported(
      "figure",
      [
        "fontFamily",
        "fontSizePt",
        "lineSpacing",
        "bold",
        "italic",
        "underline",
        "color",
        "shading",
        "spaceBeforePt",
        "spaceAfterPt",
        "indentLeftMm",
        "indentRightMm",
        "firstLineIndentMm",
        "hangingIndentMm",
        "keepWithNext",
        "pageBreakBefore",
        "borderWidthPt",
        "borderColor",
      ],
      "figures take alignment only",
    );
  }

  // Running footer with the page number; the header stays empty.
  const footer = get("footer") ?? {};
  const pageNumber = get("pageNumber") ?? {};
  const footerColor = color("awfooter", pageNumber.color ?? footer.color);
  const footerFont = fontCommands({ ...footer, ...pageNumber }, footerColor);
  const slot = { left: "L", right: "R", center: "C", justify: "C" }[
    footer.alignment ?? "center"
  ];
  out.push(
    "\\fancyhf{}",
    "\\renewcommand{\\headrulewidth}{0pt}",
    `\\fancyfoot[${slot}]{{${footerFont}\\thepage}}`,
    "\\pagestyle{fancy}",
    // \maketitle switches the first page to the plain style.
    `\\fancypagestyle{plain}{\\fancyhf{}\\renewcommand{\\headrulewidth}{0pt}\\fancyfoot[${slot}]{{${footerFont}\\thepage}}}`,
  );
  wholly("header", "exports have no running header content to style");
  unsupported(
    "footer",
    [
      "lineSpacing",
      "spaceBeforePt",
      "spaceAfterPt",
      "indentLeftMm",
      "indentRightMm",
      "firstLineIndentMm",
      "hangingIndentMm",
      "keepWithNext",
      "pageBreakBefore",
      "underline",
      "shading",
      "borderWidthPt",
      "borderColor",
    ],
    "the footer takes font and alignment settings only",
  );

  const link = get("hyperlink");
  if (link) {
    const lc = color("awlink", link.color);
    if (lc) {
      out.push(
        `\\AtBeginDocument{\\hypersetup{colorlinks=true,urlcolor=${lc},linkcolor=${lc},citecolor=${lc}}}`,
      );
    }
    unsupported(
      "hyperlink",
      ["fontFamily", "fontSizePt", "bold", "italic", "underline", "shading"],
      "hyperref styles links by colour only",
    );
  }

  if (code?.fontSizePt !== undefined) {
    const size = `\\fontsize{${num(code.fontSizePt)}pt}{${line(code.fontSizePt)}pt}\\selectfont`;
    out.push(
      `\\AtBeginEnvironment{verbatim}{${size}}`,
      `\\AtBeginEnvironment{Highlighting}{${size}}`,
    );
  }
  if (code) {
    unsupported(
      "code",
      [
        "bold",
        "italic",
        "underline",
        "color",
        "shading",
        "lineSpacing",
        "alignment",
        "spaceBeforePt",
        "spaceAfterPt",
        "indentLeftMm",
        "indentRightMm",
        "firstLineIndentMm",
        "hangingIndentMm",
        "keepWithNext",
        "pageBreakBefore",
        "borderWidthPt",
        "borderColor",
      ],
      "code takes a monospace font and block size only",
    );
  }

  // Colour definitions must precede their first use.
  const definitions = [...colors.values()];
  const insertAt = out.indexOf("\\usepackage{xcolor}") + 1;
  out.splice(insertAt, 0, ...definitions);
  return { tex: `${out.join("\n")}\n`, warnings };
}
