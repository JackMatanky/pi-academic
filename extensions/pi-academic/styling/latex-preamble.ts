const num = (value: number) => `${+value.toFixed(3)}`;

const line = (size: number) => num(size * 1.2);

function fontCommands(
  props: ComponentStyle,
  color: string | undefined,
): string {
  let out = "";

  if (props.fontSizePt !== undefined) {
    out += `\\fontsize{${num(props.fontSizePt)}pt}{${line(props.fontSizePt)}pt}\\selectfont`;
  }

  if (props.bold !== undefined) out += props.bold ? "\\bfseries" : "\\mdseries";

  if (props.italic !== undefined)
    out += props.italic ? "\\itshape" : "\\upshape";

  if (color) out += `\\color{${color}}`;

  return out;
}

interface LatexContext {
  design: StyleDesign;
  explicit: ExplicitProps;
  out: string[];
  warnings: string[];
  get(name: ComponentName): ComponentStyle | undefined;
  color(id: string, value: string | undefined): string | undefined;
  colors: Map<string, string>;
}

function createLatexContext(
  design: StyleDesign,
  explicit: ExplicitProps,
): LatexContext {
  const warnings: string[] = [];
  const colors = new Map<string, string>();

  return {
    design,
    explicit,
    out: ["% Generated by Academic Writer from design.json"],
    warnings,
    colors,
    get: (name) => design.components[name],
    color: (id, value) => {
      if (!value) return undefined;

      if (!colors.has(id)) {
        colors.set(
          id,
          `\\definecolor{${id}}{HTML}{${value.slice(1).toUpperCase()}}`,
        );
      }

      return id;
    },
  };
}

function applyPageAndBody(ctx: LatexContext): void {
  const { out, color, get } = ctx;

  out.push(
    "\\usepackage{iftex}",
    "\\usepackage{xcolor}",
    "\\usepackage{colortbl}",
    "\\usepackage{setspace}",
    "\\usepackage{etoolbox}",
    "\\usepackage{titlesec}",
    "\\usepackage{titling}",
    "\\usepackage{fancyhdr}",
    "\\usepackage{caption}",
  );

  const body = get("body") ?? {};
  const bodyColor = color("awbody", body.color);
  const fontLines: string[] = [];

  if (body.fontFamily) {
    fontLines.push(
      `\\IfFontExistsTF{${body.fontFamily}}{\\setmainfont{${body.fontFamily}}}{}`,
    );
  }

  const code = get("code");

  if (code?.fontFamily) {
    fontLines.push(
      `\\IfFontExistsTF{${code.fontFamily}}{\\setmonofont{${code.fontFamily}}}{}`,
    );
  }

  if (fontLines.length) {
    out.push("\\iftutex", "\\usepackage{fontspec}", ...fontLines, "\\fi");
  }

  if (body.alignment && ALIGN_COMMAND[body.alignment]) {
    out.push(`\\AtBeginDocument{${ALIGN_COMMAND[body.alignment]}}`);
  }

  if (body.firstLineIndentMm !== undefined) {
    out.push(
      `\\AtBeginDocument{\\setlength{\\parindent}{${num(body.firstLineIndentMm)}mm}}`,
    );
  }

  if (body.spaceAfterPt !== undefined) {
    out.push(
      `\\AtBeginDocument{\\setlength{\\parskip}{${num(body.spaceAfterPt)}pt}}`,
    );
  }

  if (bodyColor) out.push(`\\AtBeginDocument{\\color{${bodyColor}}}`);
}

function applyHeadings(ctx: LatexContext): void {
  const { out, color, get, explicit } = ctx;

  HEADING_COMMANDS.forEach(([name, command], index) => {
    const props = get(name);

    if (!props) return;

    const hc = color(`awheading${index + 1}`, props.color);
    const align = props.alignment ? ALIGN_COMMAND[props.alignment] : "";
    const underline = props.underline ? "\\underline" : "";

    out.push(
      `\\titleformat{\\${command}}[hang]{\\normalfont${fontCommands(props, hc)}${align}}{\\the${command}}{1em}{${underline}}`,
      `\\titlespacing*{\\${command}}{${num(props.indentLeftMm ?? 0)}mm}{${num(props.spaceBeforePt ?? 12)}pt}{${num(props.spaceAfterPt ?? 6)}pt}`,
    );

    if (props.pageBreakBefore) {
      out.push(`\\pretocmd{\\${command}}{\\clearpage}{}{}`);
    }

    if (props.keepWithNext === false && explicit.has(name)) {
      ctx.warnings.push(
        `latex: components.${name}.keepWithNext=false is not applied; titlesec always keeps headings with the next paragraph`,
      );
    }
  });

  const title = get("title");

  if (title) {
    const tc = color("awtitle", title.color);

    const env = {
      left: "flushleft",
      right: "flushright",
      center: "center",
      justify: "center",
    }[title.alignment ?? "center"];

    out.push(
      `\\pretitle{${title.spaceBeforePt ? `\\vspace*{${num(title.spaceBeforePt)}pt}` : ""}\\begin{${env}}${fontCommands(title, tc)}}`,
      `\\posttitle{\\par\\end{${env}}${title.spaceAfterPt ? `\\vskip ${num(title.spaceAfterPt)}pt` : ""}}`,
    );
  }

  const abstract = get("abstractBody");

  if (abstract) {
    const ac = color("awabstract", abstract.color);

    const spacing =
      abstract.lineSpacing !== undefined
        ? `\\setstretch{${num(abstract.lineSpacing)}}`
        : "";

    const align = abstract.alignment ? ALIGN_COMMAND[abstract.alignment] : "";

    out.push(
      `\\AtBeginEnvironment{abstract}{${fontCommands(abstract, ac)}${spacing}${align}}`,
    );
  }
}

function applyNotes(ctx: LatexContext): void {
  const { out, color, get, explicit } = ctx;

  const quote = get("blockQuote");

  if (quote) {
    const qc = color("awquote", quote.color);
    out.push(
      `\\renewenvironment{quote}{\\list{}{\\leftmargin=${num(quote.indentLeftMm ?? 10)}mm\\rightmargin=${num(quote.indentRightMm ?? 0)}mm\\topsep=${num(quote.spaceBeforePt ?? 6)}pt\\partopsep=0pt}\\item\\relax${fontCommands(quote, qc)}${quote.lineSpacing !== undefined ? `\\setstretch{${num(quote.lineSpacing)}}` : ""}}{\\endlist\\vspace{${num(quote.spaceAfterPt ?? 0)}pt}}`,
    );
  }

  const footnote = get("footnoteText");

  if (footnote) {
    const fc = color("awfootnote", footnote.color);

    const leading =
      footnote.fontSizePt === undefined
        ? undefined
        : footnote.fontSizePt * 1.2 * (footnote.lineSpacing ?? 1);

    const { fontSizePt: _size, ...unsized } = footnote;
    out.push("\\makeatletter");

    if (footnote.fontSizePt !== undefined && leading !== undefined) {
      out.push(
        `\\renewcommand\\footnotesize{\\@setfontsize\\footnotesize{${num(footnote.fontSizePt)}pt}{${num(leading)}pt}${fontCommands(unsized, fc)}}`,
      );
    } else if (fontCommands(footnote, fc)) {
      out.push(`\\apptocmd{\\footnotesize}{${fontCommands(footnote, fc)}}{}{}`);
    }

    out.push("\\makeatother");

    if (
      footnote.fontSizePt === undefined &&
      footnote.lineSpacing !== undefined &&
      explicit.get("footnoteText")?.has("lineSpacing")
    ) {
      ctx.warnings.push(
        "latex: components.footnoteText.lineSpacing is not applied; set fontSizePt too so the footnote leading can be computed",
      );
    }

    if (footnote.spaceAfterPt !== undefined) {
      out.push(`\\setlength{\\footnotesep}{${num(footnote.spaceAfterPt)}pt}`);
    }
  }

  const mark = get("footnoteReference");

  if (mark) {
    const mc = color("awfnmark", mark.color);
    const style = fontCommands(mark, mc);

    if (style) {
      out.push(
        "\\makeatletter",
        `\\renewcommand\\@makefnmark{\\hbox{\\@textsuperscript{\\normalfont${style}\\@thefnmark}}}`,
        "\\makeatother",
      );
    }
  }

  const bib = get("bibliography");

  if (bib) {
    const bc = color("awbib", bib.color);

    const spacing =
      bib.lineSpacing !== undefined
        ? `\\setstretch{${num(bib.lineSpacing)}}`
        : "";

    const style = `${fontCommands(bib, bc)}${spacing}`;

    if (style) out.push(`\\AtBeginEnvironment{CSLReferences}{${style}}`);
  }
}

function applyBlocks(ctx: LatexContext): void {
  const { out, color, get } = ctx;
  const lists = [get("orderedList"), get("bulletList")];

  if (lists.some(Boolean)) {
    out.push("\\usepackage{enumitem}");
    (["orderedList", "bulletList"] as const).forEach((name, index) => {
      const props = lists[index];

      if (!props) return;
      const env = name === "orderedList" ? "enumerate" : "itemize";
      const options: string[] = [];

      if (props.indentLeftMm !== undefined)
        options.push(`leftmargin=${num(props.indentLeftMm)}mm`);

      if (props.spaceAfterPt !== undefined)
        options.push(`itemsep=${num(props.spaceAfterPt)}pt`);

      if (props.spaceBeforePt !== undefined)
        options.push(`topsep=${num(props.spaceBeforePt)}pt`);

      if (options.length) out.push(`\\setlist[${env}]{${options.join(",")}}`);
    });
  }

  const table = get("table");

  if (table) {
    if (table.cellPaddingMm !== undefined)
      out.push(`\\setlength{\\tabcolsep}{${num(table.cellPaddingMm)}mm}`);

    const rule = [
      table.borderWidthPt !== undefined
        ? `\\setlength{\\heavyrulewidth}{${num(table.borderWidthPt)}pt}\\setlength{\\lightrulewidth}{${num(table.borderWidthPt)}pt}`
        : "",
      table.borderColor
        ? `\\arrayrulecolor{${color("awrule", table.borderColor)}}`
        : "",
    ].join("");

    if (rule)
      out.push(`\\AtBeginDocument{\\ifdefined\\heavyrulewidth${rule}\\fi}`);
  }

  const caption = get("caption");

  if (caption) {
    const cc = color("awcaption", caption.color);
    const fontMacro = fontCommands(caption, cc);
    const options: string[] = [];

    if (fontMacro) {
      out.push(`\\DeclareCaptionFont{awcaption}{${fontMacro}}`);
      options.push("font=awcaption");
    }

    if (caption.alignment) {
      options.push(
        `justification=${{ left: "raggedright", right: "raggedleft", center: "centering", justify: "justified" }[caption.alignment]}`,
      );
    }

    if (caption.spaceBeforePt !== undefined)
      options.push(`aboveskip=${num(caption.spaceBeforePt)}pt`);

    if (caption.spaceAfterPt !== undefined)
      options.push(`belowskip=${num(caption.spaceAfterPt)}pt`);

    if (options.length) out.push(`\\captionsetup{${options.join(",")}}`);
  }

  const figure = get("figure");

  if (figure?.alignment && ALIGN_COMMAND[figure.alignment]) {
    out.push(
      `\\AtBeginEnvironment{figure}{${ALIGN_COMMAND[figure.alignment]}}`,
    );
  }

  const code = get("code");

  if (code?.fontSizePt !== undefined) {
    const size = `\\fontsize{${num(code.fontSizePt)}pt}{${line(code.fontSizePt)}pt}\\selectfont`;
    out.push(
      `\\AtBeginEnvironment{verbatim}{${size}}`,
      `\\AtBeginEnvironment{Highlighting}{${size}}`,
    );
  }
}

function applyChrome(ctx: LatexContext): void {
  const { out, color, get } = ctx;
  const footer = get("footer") ?? {};
  const pageNumber = get("pageNumber") ?? {};
  const footerColor = color("awfooter", pageNumber.color ?? footer.color);
  const footerFont = fontCommands({ ...footer, ...pageNumber }, footerColor);

  const slot = { left: "L", right: "R", center: "C", justify: "C" }[
    footer.alignment ?? "center"
  ];

  out.push(
    "\\fancyhf{}",
    "\\renewcommand{\\headrulewidth}{0pt}",
    `\\fancyfoot[${slot}]{{${footerFont}\\thepage}}`,
    "\\pagestyle{fancy}",
    `\\fancypagestyle{plain}{\\fancyhf{}\\renewcommand{\\headrulewidth}{0pt}\\fancyfoot[${slot}]{{${footerFont}\\thepage}}}`,
  );

  const link = get("hyperlink");

  if (link) {
    const lc = color("awlink", link.color);

    if (lc) {
      out.push(
        `\\AtBeginDocument{\\hypersetup{colorlinks=true,urlcolor=${lc},linkcolor=${lc},citecolor=${lc}}}`,
      );
    }
  }
}

function collectWarnings(ctx: LatexContext): void {
  for (const [name, reason] of WHOLLY_UNSUPPORTED) {
    if (ctx.explicit.has(name)) {
      ctx.warnings.push(`latex: components.${name} is not applied; ${reason}`);
    }
  }

  for (const [name, changed] of ctx.explicit) {
    const supported = SUPPORTED_PROPS[name];

    if (!supported) continue;
    const set = new Set<string>(supported);

    for (const key of changed) {
      if (!set.has(key)) {
        ctx.warnings.push(
          `latex: components.${name}.${key} is not applied; ${UNSUPPORTED_REASONS[name] ?? "unsupported in LaTeX"}`,
        );
      }
    }
  }
}

export interface BuiltPreamble {
  tex: string;
  warnings: string[];
}

export function spliceLatexColors(
  out: string[],
  colors: Iterable<string>,
): void {
  const colorList = Array.from(colors);

  if (colorList.length === 0) return;

  const insertAt = out.indexOf("\\usepackage{xcolor}") + 1;

  if (insertAt > 0) {
    out.splice(insertAt, 0, ...colorList);
  } else {
    const lastPkg = out.findLastIndex((line) =>
      line.startsWith("\\usepackage"),
    );

    const target = lastPkg >= 0 ? lastPkg + 1 : out.length;
    out.splice(target, 0, "\\usepackage{xcolor}", ...colorList);
  }
}

export function buildLatexPreamble(
  design: StyleDesign,
  explicit: ExplicitProps,
): BuiltPreamble {
  const ctx = createLatexContext(design, explicit);
  applyPageAndBody(ctx);
  applyHeadings(ctx);
  applyNotes(ctx);
  applyBlocks(ctx);
  applyChrome(ctx);
  collectWarnings(ctx);

  spliceLatexColors(ctx.out, ctx.colors.values());

  return { tex: `${ctx.out.join("\n")}\n`, warnings: ctx.warnings };
}
